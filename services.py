def get_llm_client_async() -> AsyncOpenAI:
    """Клиент для языковых моделей (OpenRouter): оценка ответов, анализ."""
    kwargs = {"api_key": OPENROUTER_API_KEY or "dummy", "base_url": OPENROUTER_BASE_URL}
    return AsyncOpenAI(**kwargs)


def get_llm_client_sync() -> OpenAI:
    """Синхронный клиент OpenRouter (для совместимости)."""
    kwargs = {"api_key": OPENROUTER_API_KEY or "dummy", "base_url": OPENROUTER_BASE_URL}
    return OpenAI(**kwargs)


def get_whisper_client_sync() -> OpenAI:
    """Клиент для Whisper (OpenAI): распознавание голоса."""
    kwargs = {"api_key": OPENAI_API_KEY or "dummy", "base_url": OPENAI_BASE_URL}
    return OpenAI(**kwargs)


def transcribe_audio(audio_bytes: bytes, filename: str = "audio.ogg") -> str:
    """Transcribe audio using OpenAI Whisper. Expects ogg/webm from browser."""
    client = get_whisper_client_sync()
    # Whisper API expects a file-like object
    import io
    f = io.BytesIO(audio_bytes)
    f.name = filename
    resp = client.audio.transcriptions.create(model="whisper-1", file=f)
    return resp.text or ""


async def evaluate_answer_async(reference_text: str, user_answer: str, prompt_content: str) -> str:
    """Run LLM evaluation of user answer against reference. Uses prompt_content with REFERENCE_TEXT and USER_ANSWER placeholders."""
    content = prompt_content.replace("REFERENCE_TEXT", reference_text).replace("USER_ANSWER", user_answer)
    client = get_llm_client_async()
    resp = await client.chat.completions.create(
        model=LLM_MODEL,
        messages=[{"role": "user", "content": content}],
    )
    return (resp.choices[0].message.content or "").strip()


def extract_score_from_result(result_text: str) -> Optional[int]:
    """Extract numeric score from result text (e.g. 'Итоговая оценка: 4' -> 4)."""
    if not result_text:
        return None
    m = re.search(r"Итоговая оценка:\s*(\d+)", result_text, re.IGNORECASE)
    return int(m.group(1)) if m else None
